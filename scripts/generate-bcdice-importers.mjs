// BCDiceのゲームシステムと翻訳を1つずつ読み込むためのimport表を生成する。
// bcdice同梱のDynamicLoaderは実行時に組み立てたパスをrequireに渡すため、バンドラが追えずブラウザで落ちる。
// 全システムをまとめて読むと11MBを超えるので、ここでgame_system_list.jsonとi18n_list.jsonから
// パスを書き出した動的importの一覧を作り、システムごとに別チャンクで読めるようにする。
import { existsSync, readFileSync, writeFileSync } from 'fs';
import * as prettier from 'prettier';

const GAME_SYSTEM_LIST_PATH = 'node_modules/bcdice/lib/bcdice/game_system_list.json';
const GAME_SYSTEM_DIR = 'node_modules/bcdice/lib/bcdice/game_system';
const I18N_LIST_PATH = 'node_modules/bcdice/lib/bcdice/i18n_list.json';
const I18N_DIR = 'node_modules/bcdice/lib/bcdice/i18n';
const OUTPUT_PATH = 'src/app/domain/dice/bcdice/bcdice-importers.generated.ts';

const collator = new Intl.Collator('en', { numeric: true, sensitivity: 'base' });

const { gameSystems } = JSON.parse(readFileSync(GAME_SYSTEM_LIST_PATH, 'utf-8'));
const classNames = [...new Set(gameSystems.map(({ className }) => className))]
  .filter((className) => {
    if (existsSync(`${GAME_SYSTEM_DIR}/${className}.js`)) return true;
    console.warn(`[generate-bcdice-importers] 見つかりません: ${className}.js`);
    return false;
  })
  .sort(collator.compare);

const { i18nList } = JSON.parse(readFileSync(I18N_LIST_PATH, 'utf-8'));
const translations = [];
for (const { baseClassName, locales } of i18nList) {
  for (const locale of locales) {
    const fileName = `${baseClassName}.${locale}.json`;
    if (!existsSync(`${I18N_DIR}/${fileName}`)) {
      console.warn(`[generate-bcdice-importers] 見つかりません: ${fileName}`);
      continue;
    }
    translations.push({ key: `${baseClassName}.${locale}`, fileName });
  }
}
translations.sort((a, b) => collator.compare(a.fileName, b.fileName));

const gameSystemEntries = classNames
  .map((className) => `  ${className}: () => import('bcdice/lib/bcdice/game_system/${className}'),`)
  .join('\n');
const translationEntries = translations
  .map(({ key, fileName }) => `  '${key}': () => import('bcdice/lib/bcdice/i18n/${fileName}'),`)
  .join('\n');

const source = `// generated by scripts/generate-bcdice-importers.mjs — do not edit

/** Loads one game system into BCDice, by the name of its class. */
export const BCDICE_GAME_SYSTEM_IMPORTERS: Readonly<Record<string, () => Promise<unknown>>> = {
${gameSystemEntries}
};

/** Loads one translation file, by \`\${baseClassName}.\${locale}\`. */
export const BCDICE_I18N_IMPORTERS: Readonly<Record<string, () => Promise<unknown>>> = {
${translationEntries}
};
`;

const prettierConfig = await prettier.resolveConfig(OUTPUT_PATH);
writeFileSync(OUTPUT_PATH, await prettier.format(source, { ...prettierConfig, filepath: OUTPUT_PATH }));
console.log(
  `[generate-bcdice-importers] システム${classNames.length}件と翻訳${translations.length}件を${OUTPUT_PATH}に出力しました`
);
