// Extracts a table from input names to labels out of the sheet archive's creation page for each system
// ({slug}_pc_making.html), and generates src/app/domain/character/import/charasheet-label-maps.generated.ts.
// The creation page HTML comes without CORS headers, so it cannot be fetched at run time; it is made static
// here, before the build. Systems with a dedicated profile carry their own labels, so only the systems
// that fall back to the generic reader are covered.
import { Window } from 'happy-dom';
import { writeFileSync } from 'fs';

// { the creation page's slug : the game value in the data }. Most are the same.
const SYSTEMS = {
  gobusla: 'gobusla',
  aeng: 'aeng',
  konosuba: 'konosuba',
  oct: 'oct',
  kmgkr: 'kmgkr',
  pugmire: 'pugmire',
  dnd4: 'dnd4',
  yukoya: 'yukoya',
  nheaven: 'nheaven',
  horabre: 'horabre',
  horabrevsp: 'horabrevsp',
  parats: 'paranoia',
  araguild: 'araguild',
  gracreland: 'gracreland',
  ryutamad: 'ryutamad',
  utakazecal: 'utakazecal',
};

const span = (c) => Math.max(1, parseInt(c.getAttribute('colspan') || '1', 10) || 1);
const cidx = (c) => {
  let i = 0,
    n = c.previousElementSibling;
  while (n) {
    i += span(n);
    n = n.previousElementSibling;
  }
  return i;
};
const norm = (t) =>
  (t || '')
    .replace(/\s+/g, ' ')
    .replace(/[：:]\s*$/, '')
    .trim();
function colH(f, DOM) {
  const cell = f.closest('td,th');
  const row = cell?.closest('tr');
  if (!cell || !row) return '';
  const idx = cidx(cell);
  let r = row.previousElementSibling;
  while (r) {
    let acc = 0;
    for (const c of [...r.children]) {
      const s = span(c);
      if (idx >= acc && idx < acc + s) {
        if (c.tagName === 'TH') {
          const t = norm(c.textContent);
          if (t && t.length <= 8) return t;
        }
        break;
      }
      acc += s;
    }
    r = r.previousElementSibling;
  }
  return '';
}
function rowH(f) {
  const cell = f.closest('td');
  let n = cell?.previousElementSibling ?? null;
  while (n) {
    if (n.tagName === 'TH') {
      const t = norm(n.textContent);
      if (t && t.length <= 10) return t;
    }
    n = n.previousElementSibling;
  }
  return '';
}

// Internal keys and keys used for sending only ever pick up unrelated labels, so they are left out.
const INTERNAL_KEY = /^(SL_|V_|chk|is_disp|dodontof_|password|phrase|data_id|base64|color$|url$|pc_id)/i;
const isInternalKey = (name) => INTERNAL_KEY.test(name) || /_id$/.test(name);

const win = new Window();
const maps = {};
for (const [slug, game] of Object.entries(SYSTEMS)) {
  try {
    const res = await fetch(`https://charasheet.vampire-blood.net/${slug}_pc_making.html`);
    if (!res.ok) {
      console.error(slug, 'HTTP', res.status);
      continue;
    }
    const doc = new win.DOMParser().parseFromString(await res.text(), 'text/html');
    const map = {};
    for (const f of doc.querySelectorAll('input[name], select[name]')) {
      const name = f.getAttribute('name') || '';
      if (!name || name.endsWith('[]') || map[name] || isInternalKey(name)) continue;
      const label = colH(f, win) || rowH(f);
      if (label) map[name] = label;
    }
    if (Object.keys(map).length > 0) {
      maps[game] = map;
      console.error(slug, '→', game, Object.keys(map).length, 'labels');
    }
  } catch (e) {
    console.error(slug, 'ERR', e.message);
  }
  await new Promise((r) => setTimeout(r, 1200));
}

const header =
  `// Generated by a script. Not to be edited by hand.\n` +
  `// The input names and labels taken from the headings of the archive's own page, looked up by the game value.\n`;
const body = `export const CHARASHEET_LABEL_MAPS: Record<string, Record<string, string>> = ${JSON.stringify(maps, null, 2)};\n`;
writeFileSync('src/app/domain/character/import/charasheet-label-maps.generated.ts', header + body);
console.error('written', Object.keys(maps).length, 'systems');
