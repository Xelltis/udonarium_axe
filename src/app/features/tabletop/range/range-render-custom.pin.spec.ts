/** A canvas that writes down every drawing call and property its 2D context is given, in order. */
function recordingCanvas(log: unknown[]): HTMLCanvasElement {
  const values = new Map<PropertyKey, unknown>();
  const context = new Proxy({} as Record<PropertyKey, unknown>, {
    get: (_target, name) =>
      values.has(name)
        ? values.get(name)
        : (...args: unknown[]) => {
            log.push([String(name), ...args]);
          },
    set: (_target, name, value) => {
      values.set(name, value);
      log.push([`${String(name)}=`, value]);
      return true;
    },
  });
  let width = 0;
  let height = 0;
  return {
    get width() {
      return width;
    },
    set width(value: number) {
      width = value;
      log.push(['width=', value]);
    },
    get height() {
      return height;
    },
    set height(value: number) {
      height = value;
      log.push(['height=', value]);
    },
    getContext: () => context,
  } as unknown as HTMLCanvasElement;
}

function settingAt(gridType: GridType, centerX: number, centerY: number, degree: number): RangeRenderSetting {
  return {
    areaWidth: 10,
    areaHeight: 10,
    range: 1,
    width: 1,
    centerX,
    centerY,
    gridSize: 50,
    type: 'CUSTOM',
    gridColor: '#FFFF00',
    rangeColor: '#000000',
    fanDegree: 0,
    degree,
    offSetX: false,
    offSetY: false,
    fillOutLine: false,
    gridType,
    isDocking: false,
  };
}

