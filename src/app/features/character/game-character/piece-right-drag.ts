import { PointerCoordinate } from '@axe/application/input/pointer-device.service';
import { capturePointer, releasePointer } from '@axe/core/input/pointer-capture';

const RIGHT_DRAG_THRESHOLD_PX = 3;

/** What a right-drag on a piece reads of the table and does with the piece's menu. */
export interface PieceRightDragHost {
  /** Whether the table is seen flat from above, the only view a right-drag aims a menu in. */
  flat(): boolean;
  /** Drops whatever the table was doing with the pointer, so the press is the piece's alone. */
  cancelTableGesture(): void;
  /** Takes away a menu the platform opened on the press. */
  closeMenu(): void;
  /** Opens the piece's menu where the drag was let go. */
  openMenu(at: PointerCoordinate): void;
}

interface RightPress {
  readonly pointerId: number;
  readonly startX: number;
  readonly startY: number;
  dragged: boolean;
}

/**
 * A press of the right button on a piece that is dragged away before it is let go, which opens the
 * piece's menu where it is let go rather than where it was pressed.
 *
 * A mark stands under the pointer while it is dragged. A press let go where it was made is left to
 * the browser's own context menu, which opens the menu the usual way.
 */
export class PieceRightDrag {
  private press: RightPress | null = null;
  private centerMarker: HTMLElement | null = null;
  private suppressionTimer: ReturnType<typeof setTimeout> | null = null;
  private suppressor: ((event: MouseEvent) => void) | null = null;

  constructor(private readonly host: PieceRightDragHost) {}

  /** Starts following a press of the right button, in the flat view only. */
  down(event: PointerEvent): void {
    if (event.button !== 2 || !this.host.flat()) return;

    this.host.cancelTableGesture();
    this.press = {
      pointerId: event.pointerId,
      startX: event.clientX,
      startY: event.clientY,
      dragged: false,
    };
    capturePointer(event.currentTarget, event.pointerId);
  }

  /** Moves the mark with the pointer, once it has gone far enough to count as a drag. */
  move(event: PointerEvent): void {
    const press = this.press;
    if (!press || press.pointerId !== event.pointerId) return;

    if (!press.dragged) {
      const dx = event.clientX - press.startX;
      const dy = event.clientY - press.startY;
      press.dragged = dx * dx + dy * dy > RIGHT_DRAG_THRESHOLD_PX * RIGHT_DRAG_THRESHOLD_PX;
      if (!press.dragged) return;
      // Some platforms raise contextmenu on the press rather than the release. Once this is
      // known to be a drag, remove that early menu and replace it at the release point.
      this.host.closeMenu();
    }

    this.showCenterMarker(event.clientX, event.clientY);
    if (event.cancelable) event.preventDefault();
  }

  /** Opens the menu where a drag is let go, keeping the browser's own menu from opening over it. */
  up(event: PointerEvent): void {
    const press = this.press;
    if (!press || press.pointerId !== event.pointerId) return;
    this.release(event);
    this.removeCenterMarker();
    this.press = null;
    if (!press.dragged) return;

    if (event.cancelable) event.preventDefault();
    event.stopPropagation();
    this.suppressNextNativeContextMenu();
    this.host.openMenu({ x: event.clientX, y: event.clientY, z: 0 });
  }

  /** Forgets a press the browser took away. */
  cancel(event: PointerEvent): void {
    if (!this.press || this.press.pointerId !== event.pointerId) return;
    this.release(event);
    this.removeCenterMarker();
    this.press = null;
  }

  /** Takes the mark and the guard on the browser's menu away, as the piece leaves the table. */
  dispose(): void {
    this.clearNativeContextMenuSuppression();
    this.removeCenterMarker();
  }

  private showCenterMarker(x: number, y: number): void {
    let marker = this.centerMarker;
    if (!marker) {
      marker = document.createElement('div');
      marker.dataset['pieceRightDragCenter'] = '';
      marker.className = 'piece-right-drag-center';
      marker.setAttribute('aria-hidden', 'true');
      document.body.appendChild(marker);
      this.centerMarker = marker;
    }
    marker.style.left = `${x}px`;
    marker.style.top = `${y}px`;
  }

  private removeCenterMarker(): void {
    this.centerMarker?.remove();
    this.centerMarker = null;
  }

  private release(event: PointerEvent): void {
    releasePointer(event.currentTarget, event.pointerId);
  }

  private suppressNextNativeContextMenu(): void {
    this.clearNativeContextMenuSuppression();
    const suppressor = (event: MouseEvent) => {
      event.preventDefault();
      event.stopImmediatePropagation();
      this.clearNativeContextMenuSuppression();
    };
    this.suppressor = suppressor;
    document.addEventListener('contextmenu', suppressor, true);
    // A contextmenu generated by this release is dispatched in the same task. Do not let this
    // guard consume a separate right click made later.
    this.suppressionTimer = setTimeout(() => this.clearNativeContextMenuSuppression(), 0);
  }

  private clearNativeContextMenuSuppression(): void {
    if (this.suppressor) {
      document.removeEventListener('contextmenu', this.suppressor, true);
      this.suppressor = null;
    }
    if (this.suppressionTimer !== null) {
      clearTimeout(this.suppressionTimer);
      this.suppressionTimer = null;
    }
  }
}
